/** 语料规模（供设置页 / 自检脚本核对，不参与取词） */
export function promptStats(): { grid: number; easy: number; review: number; total: number } {
  let grid = 0;
  TEMPLATE_LIST.forEach(function (t) {
    Object.keys(GRID_LIBRARY[t]).forEach(function (k) { grid += GRID_LIBRARY[t][k].length; });
  });
  const easy = Object.keys(FIRST_WEEK_EASY).length;
  let review = 0;
  REVIEW_LIST.forEach(function (p) {
    REVIEW_SETS[p].forEach(function (g) { review += g.length; });
  });
  return { grid: grid, easy: easy, review: review, total: grid + easy + review };
}

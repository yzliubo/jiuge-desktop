const TEMPLATE_LIST: TemplateId[] = ['standard', 'goal', 'emotion', 'simple'];
const REVIEW_LIST: ReviewPeriod[] = ['week', 'month', 'year', 'term'];

export function knownTemplate(id: string): id is TemplateId {
  return TEMPLATE_LIST.indexOf(id as TemplateId) >= 0;
}

export function knownReviewPeriod(p: string): p is ReviewPeriod {
  return REVIEW_LIST.indexOf(p as ReviewPeriod) >= 0;
}

// 与九格既有的按日轮换同口径：同一天、同一格稳定取到同一句，点「换一条」才前进。
function hashOf(text: string): number {
  let h = 0;
  for (let i = 0; i < text.length; i += 1) h = (h * 31 + text.charCodeAt(i)) % 100000;
  return h;
}

// 调用方没带日期时按本机今天兜底，否则「换一条」之外的每日轮换会退化成固定一句。
function dayKey(date: string): string {
  if (date) return date;
  const d = new Date();
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(d.getDate()).padStart(2, '0');
  return String(d.getFullYear()) + '-' + mm + '-' + dd;
}

/**
 * 取一格引导语。返回空串表示「本库不接管」，调用方应回退到领域层 diary-store.promptFor
 * （例如用户自建模板、或旧数据键 dream），保证历史行为不变。
 */
export function gridPrompt(key: string, template: string, date: string, offset: number, easy: boolean): string {
  if (easy && offset === 0 && FIRST_WEEK_EASY[key]) return FIRST_WEEK_EASY[key];
  // 第 6 格已是家庭亲子：不管用户选了哪套模板（含旧 id 为 emotion 的那套），
  // 都不该再拿「这份情绪对目标是提醒还是噪音」这类旧题来问「今天陪了谁」。
  // 仍按日期 + 换一条偏移轮换，和别的格保持同一种手感。
  if (key === 'emotion') {
    const stepFamily = Number(offset) || 0;
    const n = FAMILY_PROMPTS.length;
    const i = ((hashOf(dayKey(String(date || '')) + '|' + key) + stepFamily) % n + n) % n;
    return FAMILY_PROMPTS[i];
  }
  if (!knownTemplate(template)) return '';
  const list = GRID_LIBRARY[template][key];
  if (!list || !list.length) return '';
  const step = Number(offset) || 0;
  const idx = ((hashOf(dayKey(String(date || '')) + '|' + key) + step) % list.length + list.length) % list.length;
  return list[idx];
}

/** 复盘题组：仍是一期三问，只是按周期键换组，避免每周每月都是同一副面孔。 */
export function reviewTriplet(period: string, periodKey: string, offset: number = 0): string[] {
  if (!knownReviewPeriod(period)) return [];
  const groups = REVIEW_SETS[period];
  if (!groups.length) return [];
  const step = Number(offset) || 0;
  const idx = ((hashOf(String(periodKey || '') + '|' + period) + step) % groups.length + groups.length) % groups.length;
  const group = groups[idx];
  return group.length === 3 ? group.slice() : group.concat(['', '', '']).slice(0, 3);
}

/** 兜底用语：领域层与本地库都取不到时，仍按格位给一句，不退回统一占位语。 */
export function fallbackFor(key: string): string {
  // 第 6 格已换成家庭亲子：旧 emotion 模板里的情绪问法一律不作兜底
  if (key === 'emotion') return FAMILY_PROMPTS[0];
  const list = GRID_LIBRARY.standard[key];
  return list && list.length ? list[0] : '';
}


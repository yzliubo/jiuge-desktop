// 以日期为种子的稳定散列：同一天任何设备、任何次打开都是同一条（格志式「每日名言」）
function dailyIndex(dateKey) {
    var key = String(dateKey || "");
    var h = 5381;
    for (var i = 0; i < key.length; i += 1) {
        h = ((h << 5) + h + key.charCodeAt(i)) | 0;
    }
    return FEATURED_IDS[Math.abs(h) % FEATURED_IDS.length];
}

// 随机换一条，且保证不与当前重复（遍历全库，含扩充主题）
function randomIndex(exclude) {
    var n = QUOTES.length;
    if (n <= 1) return 0;
    var ex = typeof exclude === "number" && exclude >= 0 && exclude < n ? exclude : -1;
    if (ex < 0) return Math.floor(Math.random() * n);
    var i = Math.floor(Math.random() * (n - 1));
    return i >= ex ? i + 1 : i;
}

function pick(index) {
    var i = typeof index === "number" && index >= 0 && index < QUOTES.length ? index : 0;
    var q = QUOTES[i];
    return { index: i, text: q.text, author: q.author, long: q.text.length > 90 };
}

